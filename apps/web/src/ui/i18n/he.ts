/** "א, ב ו-ג" style join for short Hebrew lists. */
export function joinHe(items: readonly string[]): string {
  if (items.length === 0) return '';
  if (items.length === 1) return items[0]!;
  const head = items.slice(0, -1).join(', ');
  return `${head} ו${items[items.length - 1]!}`;
}
